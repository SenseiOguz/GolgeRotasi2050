/* global process, console */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import { PNG } from 'pngjs';

const root = resolve(process.env.PIXEL_QA_ROOT ?? resolve(import.meta.dirname, '../..'));
const walk = dir => existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? walk(resolve(dir, entry.name)) : [resolve(dir, entry.name)]) : [];
const canonical = file => file.replaceAll('\\', '/');
const records = new Map();
// Discover world/ui/map area manifests; absent map area is valid.
const artRoot = resolve(root, 'art');
if (existsSync(artRoot)) for (const area of readdirSync(artRoot, { withFileTypes: true }).filter(entry => entry.isDirectory())) {
  const file = resolve(artRoot, area.name, 'manifest.json');
  if (!existsSync(file)) continue;
  const manifest = JSON.parse(readFileSync(file, 'utf8'));
  if (!Array.isArray(manifest.assets)) throw new Error(`${file}: assets must be an array`);
  for (const record of manifest.assets) {
    const file = canonical(record.file);
    if (records.has(file)) throw new Error(`Duplicate manifest file: ${file}`);
    records.set(file, record);
  }
}
const files = walk(resolve(root, 'src/assets/pixel')).filter(file => file.endsWith('.png')).map(file => canonical(relative(root, file)));
const runtimeFiles = new Set(files);
const rows = [...new Set([...files, ...records.keys()])].sort().map(file => {
  const record = records.get(file);
  const present = runtimeFiles.has(file);
  const image = present ? PNG.sync.read(readFileSync(resolve(root, file))) : undefined;
  const width = record?.nativeSize?.width ?? record?.frameWidth ?? image?.width;
  const height = record?.nativeSize?.height ?? record?.frameHeight ?? image?.height;
  const tool = record?.tool ?? record?.pixelLab?.tool ?? record?.pixellab?.tool ?? record?.generation?.tool;
  const seed = record?.seed ?? record?.pixelLab?.seed ?? record?.pixellab?.seed ?? record?.generation?.seed;
  const key = record?.key ?? file.split('/').pop().replace(/\.png$/, '').replaceAll('_', '-');
  return [key, file, width && height ? `${width}x${height}` : '-', record?.frames ?? 1, file.split('/')[3] ?? '-', tool ?? '-', seed ?? '-', present ? 'present' : 'missing'];
});
const escape = value => String(value).replaceAll('|', '\\|').replace(/[\r\n]/g, ' ');
const table = [
  '| Key | File | Native size | Frames | Area | PixelLab tool | Seed | Status |',
  '|---|---|---|---|---|---|---|---|',
  ...rows.map(row => `| ${row.map(escape).join(' | ')} |`),
].join('\n');
const markdown = `# Asset Manifest\n\nGenerated by npm run assets:manifest from src/assets/pixel/** and art/*/manifest.json. Do not edit manually.\n\n${table}\n`;
writeFileSync(resolve(root, 'ASSET_MANIFEST.md'), markdown);
console.log(table);
console.log(`${rows.length} assets; ASSET_MANIFEST.md updated.`);
